app.get('/api/data', needAuth, asyncRoute(async (req, res) => {
  const me = req.user, teacher = me.role === 'teacher';
  const cols = 'id,login,name,cls,p1,p2,target';
  const students = teacher
    ? (await db.query(`select ${cols} from users where role='student' order by name`)).rows
    : (await db.query(`select ${cols} from users where id=$1`, [me.id])).rows;
  const rs = teacher
    ? (await db.query('select session_id,user_id,h,m,r,a,b from results')).rows
    : (await db.query('select session_id,user_id,h,m,r,a,b from results where user_id=$1', [me.id])).rows;
  const by = {};
  rs.forEach(x => (by[x.user_id] = by[x.user_id] || []).push(x));
  students.forEach(s => (s.results = by[s.id] || []));
  const sessions = (await db.query('select id,to_char(d, \'YYYY-MM-DD\') as d from sessions order by d')).rows;
  res.json({ me: { id: me.id, name: me.name, role: me.role }, threshold: await threshold(), sessions, students });
}));

