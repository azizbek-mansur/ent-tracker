async function start() {
  await db.query(schema);
  const server = app.listen(PORT, () => console.log(`ЕНТ-трекер запущен на порту ${PORT}`));
  const shutdown = () => server.close(() => db.end());
  process.once('SIGINT', shutdown);
  process.once('SIGTERM', shutdown);
}

start().catch(async error => {
  console.error('Не удалось запустить приложение или подключиться к PostgreSQL:', error.message);
  await db.end();
  process.exitCode = 1;
});
