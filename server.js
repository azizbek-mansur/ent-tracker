app.post('/api/sessions', needAuth, needTeacher, asyncRoute(async (req, res) => {
  const b = req.body || {};
  const ok = v => {
    if (typeof v !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(v)) return false;
    const date = new Date(v + 'T00:00:00.000Z');
    return !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === v;
  };
  if (b.d) {
    if (!ok(b.d)) return res.status(400).json({ error: 'Неверная дата' });
    const result = await db.query('insert into sessions(d) values($1) on conflict(d) do nothing', [b.d]);
    return res.json({ ok: true, added: result.rowCount });
  }
  if (!ok(b.from) || !ok(b.to)) return res.status(400).json({ error: 'Укажите даты «с» и «по»' });
  const a = Date.parse(b.from), z = Date.parse(b.to);
  if (z < a || (z - a) / 864e5 > 400) return res.status(400).json({ error: 'Период: не больше 400 дней' });
  const dates = [];
  for (let t = a; t <= z; t += 864e5) {
    const day = new Date(t).getUTCDay();
    if (day === 2 || day === 5) dates.push(new Date(t).toISOString().slice(0, 10));
  }
  const n = await transaction(async client => {
    let added = 0;
    for (const date of dates) {
      const result = await client.query('insert into sessions(d) values($1) on conflict(d) do nothing', [date]);
      added += result.rowCount;
    }
    return added;
  });
  res.json({ ok: true, added: n });
}));

