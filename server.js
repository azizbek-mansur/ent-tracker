async function createStudent(client, row, rounds) {
  const name = str(row.name, 80), cls = str(row.cls, 10);
  const target = int(row.target, 0, 140) ?? 100;
  const base = loginBase(name);
  let login = base, suffix = 1;
  while ((await client.query('select 1 from users where login=$1', [login])).rowCount) login = base + (++suffix);
  const password = makePass();
  await client.query("insert into users(login,name,cls,role,p1,p2,target,pass_hash) values($1,$2,$3,'student',$4,$5,$6,$7)",
    [login, name, cls, str(row.p1, 40), str(row.p2, 40), target, bcrypt.hashSync(password, rounds)]);
  return { name, cls, p1: str(row.p1, 40), p2: str(row.p2, 40), login, password };
}
