app.put('/api/sessions/:id/results', needAuth, needTeacher, asyncRoute(async (req, res) => {
  const sid = Number(req.params.id);
  if (!(await db.query('select 1 from sessions where id=$1', [sid])).rowCount) return res.status(404).json({ error: 'День теста не найден' });
  const rows = Array.isArray(req.body && req.body.rows) ? req.body.rows : [];
  const clean = [];
  for (const r of rows) {
    const uid = Number(r.studentId);
    const student = await db.query("select id,name from users where id=$1 and role='student'", [uid]);
    if (!student.rowCount) continue;
    if (r.blank) { clean.push({ uid, blank: true }); continue; }
    const h = int(r.h, 0, 20), m = int(r.m, 0, 10), rr = int(r.r, 0, 10), a = int(r.a, 0, 50), b = int(r.b, 0, 50);
    if ([h, m, rr, a, b].includes(null)) {
      return res.status(400).json({ error: `${student.rows[0].name}: проверьте баллы (история 0–20, грамотности 0–10, профильные 0–50)` });
    }
    clean.push({ uid, h, m, r: rr, a, b });
  }
  await transaction(async client => {
    for (const c of clean) {
      if (c.blank) {
        await client.query('delete from results where session_id=$1 and user_id=$2', [sid, c.uid]);
      } else {
        await client.query(`insert into results(session_id,user_id,h,m,r,a,b) values($1,$2,$3,$4,$5,$6,$7)
          on conflict(session_id,user_id) do update set h=excluded.h,m=excluded.m,r=excluded.r,a=excluded.a,b=excluded.b`,
        [sid, c.uid, c.h, c.m, c.r, c.a, c.b]);
      }
    }
  });
  res.json({ ok: true, saved: clean.length });
}));

